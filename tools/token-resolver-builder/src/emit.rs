//! 产物输出：JSON token 表 + 零依赖 Rust 静态表源码。

use std::fmt::Write as _;
use std::path::Path;

use crate::vote::FinalTable;

/// 写 JSON 产物：`ck3-tokens-<version>.json`。
pub fn write_json(
    out_dir: &Path,
    version: &str,
    table: &FinalTable,
    stats: serde_json::Value,
) -> Result<std::path::PathBuf, String> {
    let tokens: serde_json::Map<String, serde_json::Value> = table
        .tokens
        .iter()
        .map(|(t, n)| (format!("0x{t:04x}"), serde_json::Value::String(n.clone())))
        .collect();
    let lookup: serde_json::Map<String, serde_json::Value> = table
        .lookup
        .iter()
        .map(|(i, s)| (i.to_string(), serde_json::Value::String(s.clone())))
        .collect();
    let doc = serde_json::json!({
        "game_version": version,
        "tokens": tokens,
        "lookup": lookup,
        "stats": stats,
    });
    let path = out_dir.join(format!("ck3-tokens-{version}.json"));
    let text = serde_json::to_string_pretty(&doc).map_err(|e| e.to_string())?;
    std::fs::write(&path, text).map_err(|e| format!("write {}: {e}", path.display()))?;
    Ok(path)
}

/// 生成零依赖 Rust 静态表源码：`ck3_tokens_<version>.rs`
/// （version 中的 `.` 替换为 `_`）。
pub fn write_rust(
    out_dir: &Path,
    version: &str,
    table: &FinalTable,
) -> Result<std::path::PathBuf, String> {
    let mut src = String::new();
    writeln!(
        src,
        "//! Auto-generated by token-resolver-builder. Do not edit."
    )
    .unwrap();
    writeln!(src, "//! CK3 game version: {version}").unwrap();
    writeln!(src, "//!").unwrap();
    writeln!(
        src,
        "//! Zero-dependency static token table. Example `TokenResolver` impl:\n"
    )
    .unwrap();
    writeln!(src, "//! ```ignore").unwrap();
    writeln!(
        src,
        "//! struct Ck3Resolver;\n"
    )
    .unwrap();
    writeln!(
        src,
        "//! impl jomini::binary::TokenResolver for Ck3Resolver {{"
    )
    .unwrap();
    writeln!(
        src,
        "//!     fn resolve(&self, token: u16) -> Option<&str> {{ resolve(token) }}"
    )
    .unwrap();
    writeln!(
        src,
        "//!     fn lookup(&self, index: u32) -> Option<&str> {{ lookup(index) }}"
    )
    .unwrap();
    writeln!(src, "//! }}").unwrap();
    writeln!(src, "//! ```\n").unwrap();

    writeln!(
        src,
        "/// 16bit token -> field name，按 token 升序，供二分查找。"
    )
    .unwrap();
    writeln!(src, "pub static TOKENS: &[(u16, &str)] = &[").unwrap();
    for (t, n) in &table.tokens {
        writeln!(src, "    (0x{t:04x}, {n:?}),").unwrap();
    }
    writeln!(src, "];\n").unwrap();

    writeln!(
        src,
        "/// lookup 索引 -> 字符串，按索引升序，供二分查找。"
    )
    .unwrap();
    writeln!(src, "pub static LOOKUP: &[(u32, &str)] = &[").unwrap();
    for (i, s) in &table.lookup {
        writeln!(src, "    ({i}, {s:?}),").unwrap();
    }
    writeln!(src, "];\n").unwrap();

    writeln!(src, "/// 二分查找 token 对应的字段名。").unwrap();
    writeln!(src, "pub fn resolve(token: u16) -> Option<&'static str> {{").unwrap();
    writeln!(
        src,
        "    TOKENS.binary_search_by_key(&token, |(t, _)| *t)"
    )
    .unwrap();
    writeln!(src, "        .ok()").unwrap();
    writeln!(src, "        .map(|i| TOKENS[i].1)").unwrap();
    writeln!(src, "}}\n").unwrap();

    writeln!(src, "/// 二分查找 lookup 索引对应的字符串。").unwrap();
    writeln!(src, "pub fn lookup(index: u32) -> Option<&'static str> {{").unwrap();
    writeln!(
        src,
        "    LOOKUP.binary_search_by_key(&index, |(i, _)| *i)"
    )
    .unwrap();
    writeln!(src, "        .ok()").unwrap();
    writeln!(src, "        .map(|i| LOOKUP[i].1)").unwrap();
    writeln!(src, "}}").unwrap();

    let file_version = version.replace('.', "_");
    let path = out_dir.join(format!("ck3_tokens_{file_version}.rs"));
    std::fs::write(&path, src).map_err(|e| format!("write {}: {e}", path.display()))?;
    Ok(path)
}
